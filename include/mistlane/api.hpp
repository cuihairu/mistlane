namespace mistlane {
// MLA1 is a typed external-API contract, not a registered HTTP/TCP endpoint.
using ApiSecret = std::array<unsigned char, 32>;
using ApiSignature = std::array<unsigned char, 32>;
enum class ApiOperation { Accept, Owner };
struct ApiRequest {
    ApiOperation operation = ApiOperation::Accept;
    std::string audience, principal, key_id;
    std::uint64_t timestamp = 0;
    std::string nonce; // Exactly 32 lowercase hex digits, generated by the caller's CSPRNG.
    RecordStore::RecordKey character;
    std::string idempotency_key, payload;
    ApiSignature signature{};
    bool operator==(const ApiRequest&) const = default;
};
// The embedding application injects credentials from private local config or
// environment. No loader, CLI secret flag or real credential is supplied here.
struct ApiCredential {
    std::string principal, key_id;
    ApiSecret secret{};
    std::set<std::string> realms;
};
inline constexpr std::uint64_t api_window_seconds = 300;
bool valid_api_request(const ApiRequest& request);
std::string api_canonical(const ApiRequest& request);
ApiSignature api_sign(const ApiRequest& request, const ApiSecret& secret);
enum class ApiAuth { Ok, Invalid, UnknownCredential, Forbidden, BadSignature, Window, Replay, Clock, Full };

// Share this guard across key rotations/verifiers for the same ingress. It is
// volatile; a future multi-process deployment needs a shared durable claim.
class ApiReplayGuard {
public:
    explicit ApiReplayGuard(std::size_t capacity = 4096) : capacity_(capacity) {}
private:
    friend class ApiVerifier;
    ApiAuth claim(const ApiRequest& request, std::uint64_t now);
    using Key = std::tuple<std::string, std::string, std::string>; // audience, principal, nonce (not key_id)
    std::mutex mutex_;
    std::map<Key, std::uint64_t> expires_;
    std::uint64_t last_now_ = 0;
    std::size_t capacity_;
};
class ApiVerifier {
public:
    ApiVerifier(std::string audience, std::vector<ApiCredential> credentials, ApiReplayGuard& replay);
    ApiAuth verify(const ApiRequest& request, std::uint64_t now) const;
private:
    std::string audience_;
    std::map<std::pair<std::string, std::string>, ApiCredential> credentials_;
    ApiReplayGuard& replay_;
};

struct ApiAcceptanceKey {
    std::string audience, principal;
    RecordStore::RecordKey character;
    std::string idempotency_key;
    auto operator<=>(const ApiAcceptanceKey&) const = default;
};
struct ApiCommand {
    ApiAcceptanceKey key;
    std::string payload;
    bool operator==(const ApiCommand&) const = default;
};
struct ApiReceipt {
    ApiCommand command; // Immutable accepted command IS the pending work row.
    bool operator==(const ApiReceipt&) const = default;
};
enum class ApiCreate { Inserted, Existing, Conflict, Invalid, Full };
enum class ApiDurability { Volatile, Durable };
struct ApiAcceptance {
    ApiCreate result = ApiCreate::Invalid;
    ApiDurability durability = ApiDurability::Volatile;
    std::optional<ApiReceipt> receipt;
};
class ApiAcceptanceStore {
public:
    virtual ~ApiAcceptanceStore() = default;
    // Atomic create-or-read: receipt + command become visible together. Same
    // key/body returns Existing, changed body Conflict. Durable is legal only
    // after a durable commit, including on Existing after a lost reply/restart.
    virtual ApiAcceptance create(const ApiCommand& command) = 0;
};
class ApiMemoryAcceptanceStore final : public ApiAcceptanceStore {
public:
    explicit ApiMemoryAcceptanceStore(std::size_t capacity = 4096) : capacity_(capacity) {}
    ApiAcceptance create(const ApiCommand& command) override;
    std::size_t size() const;
private:
    mutable std::mutex mutex_;
    std::map<ApiAcceptanceKey, ApiReceipt> rows_;
    std::size_t capacity_;
};
struct ApiOwnershipReply {
    enum class Status { Found, NotFound };
    Status status = Status::NotFound;
    std::optional<HomeOwnership> current;
};
struct ApiReply {
    ApiAuth auth = ApiAuth::Invalid;
    std::optional<ApiAcceptance> acceptance;
    std::optional<ApiOwnershipReply> ownership;
};
class ApiSurface {
public:
    // Lookup must read authoritative HOME facts, never the coordinator route.
    using Lookup = std::function<std::optional<HomeOwnership>(const MigrationKey&)>;
    ApiSurface(const ApiVerifier& verifier, ApiAcceptanceStore& store, Lookup lookup)
      : verifier_(verifier), store_(store), lookup_(std::move(lookup)) {}
    ApiReply handle(const ApiRequest& request, std::uint64_t now) const;
private:
    const ApiVerifier& verifier_;
    ApiAcceptanceStore& store_;
    Lookup lookup_;
};
// MLA1 wire body: the canonical bytes followed by the raw 32-byte signature.
// Parsing is byte-exact — exactly the ten framed fields, then exactly the
// signature, nothing else. The reply framing and HTTP status mapping below
// are the transport face of the same contract.
bool parse_api_body(std::string_view body, ApiRequest& out);
std::string api_reply_body(const ApiReply& reply);
unsigned api_http_status(const ApiReply& reply);
}
