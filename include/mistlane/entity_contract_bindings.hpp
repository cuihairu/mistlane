               "      node.splice(position, 0, cloneValue(delta.value));\n"
               "    } else {\n"
               "      if (position >= node.length) return null;\n"
               "      node.splice(position, 1);\n"
               "    }\n"
               "  } else return null;\n"
               "  return { property: field.name, path, kind: delta.kind, position, value: delta.value };\n"
               "}\n";
