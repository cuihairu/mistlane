void write_file(const fs::path& root, const TemplateFile& file, std::string_view name) {
    fs::path target = root / file.path;
    fs::create_directories(target.parent_path());
    std::ofstream out(target, std::ios::binary | std::ios::trunc);
    if (!out) throw std::runtime_error("cannot create " + target.string());
    std::string content(file.content);
    constexpr std::string_view marker = "{{name}}";
    if (const auto pos = content.find(marker); pos != std::string::npos)
        content.replace(pos, marker.size(), name);
    out.write(content.data(), static_cast<std::streamsize>(content.size()));
    if (!out) throw std::runtime_error("cannot write " + target.string());
    if (file.path.ends_with(".sh")) fs::permissions(target,
        fs::perms::owner_read | fs::perms::owner_write | fs::perms::owner_exec |
        fs::perms::group_read | fs::perms::group_exec |
        fs::perms::others_read | fs::perms::others_exec,
        fs::perm_options::replace);
}
