int run_scaffold(std::string_view command, int argc, char** argv) {
    if (command != "init") return -1;
    fs::path destination = ".";
    bool have_destination = false;
    for (int i = 2; i < argc; ++i) {
        std::string_view arg(argv[i]);
        if (arg == "--help" || arg == "-h") {
            std::cout << "Usage: mistlane init [DIRECTORY]\n"
                         "Create a starter project with TCP gateway/router/worker, cross/shard, and HTTP Lua examples.\n"
                         "The destination must be empty if it already exists.\n";
            return 0;
        }
        if (arg.starts_with('-')) throw std::invalid_argument("unknown init option: " + std::string(arg));
        if (have_destination) throw std::invalid_argument("init accepts one destination directory");
        destination = fs::path(arg);
        have_destination = true;
    }

    const bool existed = fs::exists(destination);
    if (existed && !fs::is_directory(destination))
        throw std::invalid_argument("init destination is not a directory");
    if (existed && !fs::is_empty(destination))
        throw std::invalid_argument("init destination must be empty: " + destination.string());
    fs::create_directories(destination);
    fs::create_directories(destination / "var" / "run");
    fs::create_directories(destination / "var" / "log");
    const std::string name = safe_name(destination.filename().string());
    try {
        for (const auto& file : files) write_file(destination, file, name);
    } catch (...) {
        if (!existed) fs::remove_all(destination);
        throw;
    }
    std::cout << "Initialized " << name << " in " << fs::absolute(destination).string()
              << " (" << files.size() << " files)\n";
    return 0;
}
