std::string safe_name(std::string value) {
    for (char& c : value) {
        const auto ch = static_cast<unsigned char>(c);
        if (!std::isalnum(ch) && c != '-' && c != '_') c = '-';
    }
    if (value.empty()) value = "mistlane-service";
    return value;
}

